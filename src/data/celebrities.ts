export const getCelebrityBySlug = (slug: string): Celebrity | undefined => {
  return celebrities.find((c) => c.slug.toLowerCase() === slug.toLowerCase());
};

export const getFeaturedCelebrities = (): Celebrity[] => {
  return celebrities.filter((c) => (c.status ?? "active") === "active" && c.featured);
};

export const getTrendingCelebrities = (): Celebrity[] => {
  return celebrities.filter((c) => (c.status ?? "active") === "active" && c.trending);
};

export const getCelebritiesByCategory = (categorySlug: string): Celebrity[] => {
  return celebrities.filter(
    (c) =>
      (c.status ?? "active") === "active" &&
      c.categorySlug.toLowerCase() === categorySlug.toLowerCase()
  );
};

export const getCelebritiesBySubcategory = (subcategorySlug: string): Celebrity[] => {
  return celebrities.filter(
    (c) =>
      (c.status ?? "active") === "active" &&
      (c.subcategorySlug || "").toLowerCase() === subcategorySlug.toLowerCase()
  );
};
